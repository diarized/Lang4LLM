//! Lang4LLM → Rust transpiler.
//!
//! Transforms a parsed and type-checked Lang4LLM `Program` AST into
//! valid Rust 2021 source code as a `String`.
//!
//! # Usage
//!
//! ```no_run
//! use lang4llm_ast::Program;
//! use lang4llm_transpiler::transpile;
//!
//! // Assume `program` is already parsed + type-checked
//! let program: Program = todo!();
//! match transpile(&program) {
//!     Ok(rust_src) => println!("{}", rust_src),
//!     Err(errors) => eprintln!("{:?}", errors),
//! }
//! ```

