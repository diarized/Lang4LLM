use std::collections::HashMap;

use lang4llm_ast::{Item, Program, Type};
use thiserror::Error;

use crate::context::CodegenContext;
use crate::items::emit_item;

// =============================================================================
// Public API
// =============================================================================

/// Options controlling transpilation behaviour.
#[derive(Debug, Clone, Default)]
pub struct TranspileOptions {
    /// Emit a `// Generated by lang4llm-transpiler` header comment.
    pub emit_header: bool,
}

/// Error produced during transpilation.
#[derive(Debug, Error)]
pub enum TranspileError {
    /// An AST node was encountered that the transpiler does not yet support.
    #[error("unsupported AST node: {0}")]
    Unsupported(String),
    /// Generic internal error.
    #[error("internal transpiler error: {0}")]
    Internal(String),
}

/// Transpile a `Program` AST to Rust source code.
///
/// Returns `Ok(rust_source)` on success, or `Err(errors)` if any
/// transpilation errors were encountered.
pub fn transpile(program: &Program) -> Result<String, Vec<TranspileError>> {
    transpile_with_options(program, &TranspileOptions::default())
}

/// Transpile with explicit options.
pub fn transpile_with_options(
    program: &Program,
    options: &TranspileOptions,
) -> Result<String, Vec<TranspileError>> {
    // Build function return type map for string-concat detection
    let fn_return_types: HashMap<String, Type> = program
        .items
        .iter()
        .filter_map(|item| {
            if let Item::Function(f) = item {
                Some((f.name.name.clone(), f.return_type.clone()))
            } else {
                None
            }
        })
        .collect();

    let mut ctx = CodegenContext::with_fn_types(fn_return_types);
    let errors: Vec<TranspileError> = Vec::new();

    // Preamble
    ctx.writeln("#![allow(unused)]");
    ctx.writeln("#![allow(unused_variables)]");
    ctx.writeln("#![allow(dead_code)]");
    ctx.newline();

    if options.emit_header {
        ctx.writeln("// Generated by lang4llm-transpiler");
        ctx.newline();
    }

    // Emit each top-level item
    for item in &program.items {
        // We use catch_unwind to capture any unexpected panics from codegen
        // In a production compiler this would use a proper Result-threaded
        // visitor, but for Phase 3 we do best-effort.
        emit_item(item, &mut ctx);
    }

    if errors.is_empty() {
        Ok(ctx.finish())
    } else {
        Err(errors)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_empty_program() {
        use lang4llm_ast::{Program, Span};
        let program = Program {
            module: None,
            imports: vec![],
            items: vec![],
            span: Span::new(0, 0, 0, 0),
        };
        let result = transpile(&program).unwrap();
        assert!(result.contains("#![allow(unused)]"));
    }
}
